//go:build ignore

// gen writes zones.go from the IANA zone names in Go's bundled tz database
// ($GOROOT/lib/time/zoneinfo.zip). Run with `go generate ./internal/tz`.
package main

import (
	"archive/zip"
	"bytes"
	"fmt"
	"go/format"
	"log"
	"os"
	"path/filepath"
	"runtime"
	"sort"
	"strings"
)

func main() {
	z, err := zip.OpenReader(filepath.Join(runtime.GOROOT(), "lib", "time", "zoneinfo.zip"))
	if err != nil {
		log.Fatal(err)
	}
	defer z.Close()
	var names []string
	for _, f := range z.File {
		if f.FileInfo().IsDir() || strings.HasPrefix(f.Name, "posix/") || strings.HasPrefix(f.Name, "right/") {
			continue
		}
		names = append(names, f.Name)
	}
	sort.Strings(names)

	var b bytes.Buffer
	b.WriteString("// Code generated by gen.go; DO NOT EDIT.\n\npackage tz\n\n")
	b.WriteString("// Names lists every zone in the IANA tz database, including backward-compatible links.\n")
	b.WriteString("var Names = []string{\n")
	for _, n := range names {
		fmt.Fprintf(&b, "\t%q,\n", n)
	}
	b.WriteString("}\n")
	src, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile("zones.go", src, 0o644); err != nil {
		log.Fatal(err)
	}
	fmt.Printf("wrote %d zones\n", len(names))
}
